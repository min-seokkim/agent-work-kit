"""Every `awkit` command line the kit's guides show parses with awkit's own parser (F4).

A command line is inline code that starts with `awkit `, or the words after a standalone `awkit` in a code
block. Usage synopses are expanded: `[...]` is optional, `a | b` inside brackets and `a|b` within a word are
alternatives, `...` repeats. Each concrete variant is parsed without running anything, with every argument
made optional so that a mention of a bare command such as `awkit review check` still parses. A word in
capitals or in angle brackets is a placeholder; where the parser offers choices, it takes the first one.
The line fails when one of its words appears in no variant that parses: an unknown command or option.
"""

import argparse
import contextlib
import io
import itertools
import re
import shlex
import unittest
from pathlib import Path
from unittest import mock

from awkit.cli import _parser

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "kit"
# Inline code that names a format, not a command.
NOT_COMMANDS = {"awkit NAME (ENTRIES): "}
GUARD_TABLE = re.compile(r"<!-- guard table: generated by scripts/guard_map\.py -->.*?<!-- end of guard table -->", re.S)
FENCE = re.compile(r"^```[^\n]*\n(.*?)^```", re.S | re.M)
SPAN = re.compile(r"(`+)(.+?)\1")
SHELL_END = {"|", "||", "&&", ";", ")", ">", ">>", "2>", "2>&1"}
PLACEHOLDER = re.compile(r"<[^>]+>|[A-Z][A-Z0-9_-]*|\$\w+|YYYY-MM-DD")


class ParseError(Exception):
    pass


def documented_commands(kit=KIT):
    """[(file, command text)] for every `awkit` command shown in the kit's Markdown files."""
    found = []
    for path in sorted(kit.rglob("*.md")):
        text = GUARD_TABLE.sub("", path.read_text(encoding="utf-8"))
        name = path.relative_to(kit).as_posix()
        for block in FENCE.findall(text):
            for line in block.splitlines():
                words = _split(line)
                if "awkit" in words:
                    rest = words[words.index("awkit") + 1:]
                    end = next((i for i, word in enumerate(rest) if word in SHELL_END), len(rest))
                    found.append((name, " ".join(["awkit", *rest[:end]])))
        for _, span in SPAN.findall(FENCE.sub("", text)):
            if span.startswith("awkit ") and span not in NOT_COMMANDS:
                found.append((name, span.strip()))
    return found


def _split(line):
    try:
        return shlex.split(line.replace("\\", "/"))
    except ValueError:
        return line.split()


def _structure(words):
    """Nested synopsis: a list of items; an item is ("word", [alternatives]) or ("optional", [sequences])."""
    stack, alternatives = [[]], [[]]
    for word in words:
        while word.startswith("[") and word != "[":
            stack.append([]), alternatives.append([])
            word = word[1:]
        word = word.removesuffix("...")
        closes = len(word) - len(word.rstrip("]"))
        word = word.rstrip("]")
        if word == "[":
            stack.append([]), alternatives.append([])
        elif word == "|":
            if len(stack) == 1:
                raise ParseError("an unbracketed ' | ' between words; write alternatives inside [ ] or as a|b")
            alternatives[-1].append(stack[-1])
            stack[-1] = []
        elif word:
            stack[-1].append(("word", word.split("|") if "|" in word and not word.startswith("|") else [word]))
        for _ in range(closes):
            if len(stack) == 1:
                raise ParseError("an unmatched ]")
            sequence, options = stack.pop(), alternatives.pop()
            stack[-1].append(("optional", [*options, sequence]))
    if len(stack) != 1:
        raise ParseError("an unmatched [")
    return stack[0]


def _variants(sequence):
    """Every concrete word list the synopsis allows, each word tagged with its position in the synopsis."""
    choices = []
    for index, (kind, value) in enumerate(sequence):
        if kind == "word":
            choices.append([[(f"{id(sequence)}:{index}:{word}", word)] for word in value])
        else:
            choices.append([[]] + [variant for option in value for variant in _variants(option)])
    return [[word for part in combination for word in part] for combination in itertools.product(*choices)]


def _all_words(sequence):
    words = set()
    for index, (kind, value) in enumerate(sequence):
        if kind == "word":
            words.update(f"{id(sequence)}:{index}:{word}" for word in value)
        else:
            for option in value:
                words |= _all_words(option)
    return words


def _relax(parser):
    """Make every argument optional, so that a command named without its arguments still parses, and accept
    only full option names, so that a documented abbreviation fails like an unknown option."""
    parser.allow_abbrev = False
    for action in parser._actions:
        action.required = False
        if isinstance(action, argparse._SubParsersAction):
            for sub in action.choices.values():
                _relax(sub)


def _raise(self, message):
    raise ParseError(message)


def parse(parser, argv):
    """Parse argv without running it; raise ParseError naming the first unknown word."""
    # A trailing `--` ends the options before file names that a pipe supplies.
    argv = list(argv[:-1] if argv[-1:] == ["--"] else argv)
    for _ in range(len(argv) + 1):
        try:
            with mock.patch.object(argparse.ArgumentParser, "error", _raise), \
                    contextlib.redirect_stdout(io.StringIO()):
                _, extra = parser.parse_known_args(argv)
        except SystemExit as exc:  # --help
            if exc.code in (0, None):
                return
            raise ParseError(f"exit {exc.code}") from None
        except ParseError as exc:
            # A placeholder stands for the parser's first choice, or for 1 where it expects a number.
            found = re.search(r"invalid (?:choice|int value|float value): '([^']*)'(?: \(choose from (.+)\))?", str(exc))
            if not found or not PLACEHOLDER.fullmatch(found.group(1)) or found.group(1) not in argv:
                raise
            value = found.group(2).split(",")[0].strip().strip("'") if found.group(2) else "1"
            argv[argv.index(found.group(1))] = value
            continue
        if extra:
            raise ParseError(f"unrecognized arguments: {' '.join(extra)}")
        return
    raise ParseError("placeholders did not resolve")


def problems(parser, commands):
    """[(file, command, reason)] for each command with a word that no parsing variant contains."""
    found = []
    for name, command in commands:
        try:
            sequence = _structure(_split(command)[1:])
        except ParseError as exc:
            found.append((name, command, str(exc)))
            continue
        covered, errors = set(), []
        for variant in _variants(sequence):
            try:
                parse(parser, [word for _, word in variant])
            except ParseError as exc:
                errors.append(str(exc))
            else:
                covered.update(key for key, _ in variant)
        missing = sorted({key.split(":", 2)[2] for key in _all_words(sequence) - covered})
        if missing:
            found.append((name, command, f"{', '.join(missing)} parse in no variant; first error: {errors[0]}"))
    return found


def relaxed_parser():
    parser = _parser()
    _relax(parser)
    return parser


def subparser(parser, *path):
    for name in path:
        parser = next(action for action in parser._actions
                      if isinstance(action, argparse._SubParsersAction)).choices[name]
    return parser


class KitCommandTests(unittest.TestCase):
    def test_every_documented_command_parses(self):
        commands = documented_commands()
        self.assertGreater(len(commands), 100)
        self.assertEqual(problems(relaxed_parser(), commands), [])

    def test_a_renamed_option_fails(self):
        parser = relaxed_parser()
        check = subparser(parser, "review", "check")
        action = check._option_string_actions.pop("--runs-root")
        action.option_strings = ["--runs-dir"]
        check._option_string_actions["--runs-dir"] = action
        found = problems(parser, documented_commands())
        self.assertTrue(found)
        self.assertTrue(all("--runs-root" in reason for _, _, reason in found), found)

    def test_unknown_commands_and_options_fail(self):
        parser = relaxed_parser()
        commands = [("x.md", "awkit review chek HEAD"), ("x.md", "awkit doctor [--jsn]"),
                    ("x.md", "awkit channel wait ROLE MODE [--max SECONDS] [--keep-awak]"),
                    ("x.md", "awkit review verify|accep RUN")]
        reasons = [reason for _, _, reason in problems(parser, commands)]
        self.assertEqual(len(reasons), 4, reasons)
        for word, reason in zip(("chek", "--jsn", "--keep-awak", "accep"), reasons, strict=True):
            self.assertIn(word, reason)

    def test_synopses_expand_to_every_alternative(self):
        parser = relaxed_parser()
        commands = [("x.md", "awkit review [--repo DIR] storage [--runs-root DIR] [--json | --summary]"),
                    ("x.md", "awkit review verify|accept RUN"),
                    ("x.md", "awkit <command> --help"), ("x.md", "awkit hook [EVENT] [--skip RULE]... [--kit-hooks]")]
        self.assertEqual(problems(parser, commands), [])


if __name__ == "__main__":
    unittest.main()
